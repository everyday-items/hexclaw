// Command contractgen generates TypeScript runtime validators from a
// versioned JSON Schema. The checked-in output is deterministic and --check
// turns schema/consumer drift into a CI failure.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
)

func main() {
	schemaPath := flag.String("schema", "api/view_contracts/k12-image-task.v1.schema.json", "input JSON Schema")
	outPath := flag.String("out", "../hexclaw-desktop/src/contracts/generated/k12-image-task.v1.ts", "generated TypeScript")
	check := flag.Bool("check", false, "fail if generated output differs")
	flag.Parse()

	raw, err := os.ReadFile(*schemaPath)
	if err != nil { fatal(err) }
	var schema any
	if err := json.Unmarshal(raw, &schema); err != nil { fatal(fmt.Errorf("decode schema: %w", err)) }
	canonical, err := json.MarshalIndent(schema, "", "  ")
	if err != nil { fatal(err) }
	generated := render(canonical)
	if *check {
		current, readErr := os.ReadFile(*outPath)
		if readErr != nil || !bytes.Equal(current, generated) {
			fatal(fmt.Errorf("generated contract drift: run go run ./cmd/contractgen -schema %s -out %s", *schemaPath, *outPath))
		}
		return
	}
	if err := os.MkdirAll(filepath.Dir(*outPath), 0o755); err != nil { fatal(err) }
	if err := os.WriteFile(*outPath, generated, 0o644); err != nil { fatal(err) }
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "contractgen:", err)
	os.Exit(1)
}

